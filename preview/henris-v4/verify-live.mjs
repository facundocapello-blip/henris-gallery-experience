import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { readFile } from 'node:fs/promises';
const root=process.argv[2]||'https://facundocapello-blip.github.io/henris-gallery-experience/';
const url=new URL('henris-v4/',root.endsWith('/')?root:root+'/').href;
const source=await readFile(new URL('./index.html',import.meta.url),'utf8');
const mapping=JSON.parse(source.match(/<script id="mapping-source" type="application\/json">([\s\S]*?)<\/script>/)[1]);
assert.equal(mapping.sections.reduce((n,s)=>n+s.items.length,0),66,'All documented fields preserved');
assert.deepEqual(mapping.sections.map(s=>[s.table,s.items.length]),[['Pedidos',19],['Pedido_Items',26],['Pagos',14],['Clientes',7]]);
assert.equal(JSON.parse(source.match(/const essential=new Set\((\[[\s\S]*?\])\);/)[1]).length,29);
await mkdir('test-results',{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:process.env.HENRIS_BROWSER_EXECUTABLE||undefined,args:['--no-sandbox']});
try{
 for(const width of [1440,768,390]){
  const page=await browser.newPage({viewport:{width,height:900},isMobile:width===390,hasTouch:width===390});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  const response=await page.goto(url,{waitUntil:'networkidle',timeout:35000});
  assert.equal(response.status(),200);
  assert.equal(await page.locator('body').getAttribute('data-preview'),'henris-v4');
  assert.equal(await page.locator('#mode-main').getAttribute('aria-pressed'),'true');
  assert.equal(await page.locator('#fields .field').count(),29);
  assert.equal(await page.locator('.relation-card').count(),4);
  await page.locator('#tabs [data-tab="Pagos"]').click();
  assert.equal(await page.locator('#fields .field').count(),7);
  await page.locator('#fields [data-field="Importe"]').click();
  assert.deepEqual(await page.locator('#origins .column-name').allInnerTexts(),['SEÑA','SEGUNDA PARTE PAGO']);
  await page.locator('#mode-all').click();
  await page.locator('#tabs [data-tab="todos"]').click();
  assert.equal(await page.locator('#fields .field').count(),66);
  await page.locator('#search').fill('Saldo_Pendiente');
  assert.equal(await page.locator('#fields .field').count(),1);
  await page.locator('#search').fill('');
  await page.locator('#mode-main').click();
  assert.equal(await page.locator('#fields .field').count(),29);
  assert.match(await page.locator('#demo-due').innerText(),/85.000/);
  assert.match(await page.locator('#demo-paid').innerText(),/80.000/);
  await page.locator('#demo-taller-toggle').click();
  assert.equal(await page.locator('#demo-workshop').isVisible(),true);
  await page.locator('#demo-work-done').click();
  assert.equal(await page.locator('#demo-work-status').innerText(),'Lista para entregar');
  await page.locator('#demo-payment-toggle').click();
  assert.equal(await page.locator('#demo-payment-form').isVisible(),true);
  await page.locator('#demo-payment-amount').fill('90000');
  await page.locator('#demo-payment-confirm').check();
  await page.locator('#demo-payment-submit').click();
  assert.match(await page.locator('#demo-payment-error').innerText(),/supera el saldo/);
  assert.match(await page.locator('#demo-due').innerText(),/85.000/,'Invalid payment did not mutate total');
  await page.locator('#demo-payment-amount').fill('25000');
  await page.locator('#demo-payment-submit').click();
  assert.match(await page.locator('#demo-paid').innerText(),/105.000/);
  assert.match(await page.locator('#demo-due').innerText(),/60.000/);
  assert.equal(await page.locator('.demo-payment-entry').count(),3);
  await page.locator('#demo-payment-undo').click();
  assert.match(await page.locator('#demo-due').innerText(),/85.000/);
  assert.equal(await page.locator('.demo-payment-entry').count(),2);
  await page.locator('#demo-payment-toggle').click();
  await page.locator('#demo-payment-amount').fill('85000');
  await page.locator('#demo-payment-confirm').check();
  await page.locator('#demo-payment-submit').click();
  assert.match(await page.locator('#demo-due').innerText(),/0/);
  assert.equal(await page.locator('#demo-payment-state').innerText(),'Saldado');
  assert.equal(await page.locator('#demo-payment-toggle').isDisabled(),true);
  await page.locator('#demo-reset').click();
  assert.match(await page.locator('#demo-due').innerText(),/85.000/);
  assert.equal(await page.locator('#demo-work-status').innerText(),'En taller');
  assert.equal(await page.locator('#demo-payment-state').innerText(),'Parcial');
  assert.equal(await page.locator('.demo-payment-entry').count(),2);
  const metrics=await page.evaluate(()=>({viewport:window.innerWidth,scroll:document.documentElement.scrollWidth}));
  assert.ok(metrics.scroll<=metrics.viewport+1,'Horizontal overflow '+JSON.stringify(metrics));
  assert.deepEqual(errors,[],'JavaScript errors at '+width);
  await page.screenshot({path:'test-results/henris-v4-'+width+'-inicio.png',fullPage:false});
  await page.locator('#demo').scrollIntoViewIfNeeded();
  await page.screenshot({path:'test-results/henris-v4-'+width+'-demo.png',fullPage:false});
  await page.close();
 }
 console.log('SUCCESS Henris V4: original 66 fields / 29 essentials, mobile-first mappings, 2 artworks, partial/final/invalid payments, undo, reset and workshop at 390/768/1440 px.');
}finally{await browser.close();}
